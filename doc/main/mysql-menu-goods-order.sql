--
-- 执行顺序：Part 1 菜单 → Part 2 可选的角色授权 → Part 3 自检
-- 目标库：与 .env 的 DB_DATABASE 一致；MySQL 8.0.19+（upsert 别名语法）
-- ============================================================================


