-- 与完整 DDL 的关系：
--   完整脚本 doc/main/mysql-ddl-goods-order.sql 的 Part 2 已包含这 16 行菜单；
--   本文件把它单独抽出来，并改成**幂等 upsert**（重复执行只覆盖菜单展示字段，
