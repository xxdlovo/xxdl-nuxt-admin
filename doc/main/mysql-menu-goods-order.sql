-- ============================================================================
-- Part 2：角色授权（可选）
--
-- 说明：
-- - 管理员账号（sys_user.is_admin = 1）走「全量菜单」分支，不需要任何授权；
-- - 其它角色只有在 sys_role_menu 里有记录才会看到对应菜单与权限；
-- - sys_role_menu 只有主键、没有 (role_id, menu_id) 唯一键，所以幂等做法是
--   「先删掉这批 (角色 × 菜单) 关联，再统一插入」——因此下面是 DELETE + INSERT 两段。
--
-- 授权矩阵（只给只读能力，写操作权限仍只属于管理员）：
--   部门经理 dept_manager：交易中心 + 商品管理(查询) + 订单管理(查询) + 商城 + 我的订单
--   业务运营 operator    ：同上
--   审计员   auditor     ：交易中心 + 订单管理(查询) + 商城 + 我的订单
--   访客     guest       ：不授（自助页仍可从右上角头像菜单进入）
-- 如需调整，改下面的 role id 列表或菜单 id 列表即可。
-- ============================================================================

-- 2.1 清掉本脚本负责的这批关联（可重复执行的关键）
DELETE FROM `sys_role_menu`
WHERE `menu_id` IN (
  '10000000-0000-0000-0000-000000001100',
  '10000000-0000-0000-0000-000000001101',
  '10000000-0000-0000-0000-000000001102',
  '10000000-0000-0000-0000-000000001111',
  '10000000-0000-0000-0000-000000001112',
  '10000000-0000-0000-0000-000000001121',
  '10000000-0000-0000-0000-000000001131'
)
AND `role_id` IN (
  '20000000-0000-0000-0000-000000000002',
  '20000000-0000-0000-0000-000000000003',
  '20000000-0000-0000-0000-000000000004'
);

-- 2.2 部门经理 / 业务运营：目录 + 商品查询 + 订单查询 + 两个自助页
INSERT INTO `sys_role_menu`
  (`id`, `role_id`, `menu_id`, `status`, `remark`, `created_by`, `updated_by`, `is_deleted`)
SELECT UUID(), r.`id`, m.`id`, 1, '交易中心菜单授权',
       '30000000-0000-0000-0000-000000000001', '30000000-0000-0000-0000-000000000001', 0
FROM `sys_role` r
JOIN `sys_menu` m ON m.`id` IN (
  '10000000-0000-0000-0000-000000001100',
  '10000000-0000-0000-0000-000000001101',
  '10000000-0000-0000-0000-000000001102',
  '10000000-0000-0000-0000-000000001111',
  '10000000-0000-0000-0000-000000001112',
  '10000000-0000-0000-0000-000000001121',
  '10000000-0000-0000-0000-000000001131'
)
WHERE r.`id` IN (
  '20000000-0000-0000-0000-000000000002',
  '20000000-0000-0000-0000-000000000003'
)
AND r.`is_deleted` = 0;

-- 2.3 审计员：目录 + 订单查询 + 两个自助页（不给商品管理）
INSERT INTO `sys_role_menu`
  (`id`, `role_id`, `menu_id`, `status`, `remark`, `created_by`, `updated_by`, `is_deleted`)
SELECT UUID(), r.`id`, m.`id`, 1, '交易中心菜单授权',
       '30000000-0000-0000-0000-000000000001', '30000000-0000-0000-0000-000000000001', 0
FROM `sys_role` r
JOIN `sys_menu` m ON m.`id` IN (
  '10000000-0000-0000-0000-000000001100',
  '10000000-0000-0000-0000-000000001111',
  '10000000-0000-0000-0000-000000001112',
  '10000000-0000-0000-0000-000000001121',
  '10000000-0000-0000-0000-000000001131'
)
WHERE r.`id` = '20000000-0000-0000-0000-000000000004'
AND r.`is_deleted` = 0;


-- ============================================================================
-- Part 3：执行结果自检
-- 预期：菜单 16 行；授权行数 = 7×2 + 5 = 19
-- ============================================================================

SELECT COUNT(*) AS `交易中心菜单行数(应为16)` FROM sys_menu
WHERE `id` LIKE '10000000-0000-0000-0000-0000000011%';

SELECT r.`code` AS `角色`, COUNT(*) AS `授权菜单数`
FROM `sys_role_menu` rm
JOIN `sys_role` r ON r.`id` = rm.`role_id`
WHERE rm.`menu_id` LIKE '10000000-0000-0000-0000-0000000011%'
GROUP BY r.`code`
ORDER BY r.`code`;

-- 侧边栏可见性核对：目录 + 类型不为按钮的页面
SELECT `id`, `parent_id`, `name`, `code`, `type`, `path`, `sort_order`, `visible`, `status`
FROM `sys_menu`
WHERE `id` LIKE '10000000-0000-0000-0000-0000000011%' AND `type` IN (0, 1)
ORDER BY `sort_order`, `id`;
