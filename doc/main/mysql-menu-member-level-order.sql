-- ============================================================================
-- 会员开通记录（会员等级购买 / 续费单据）后台侧边栏菜单：独立、可重复执行的脚本
--
-- 与完整 DDL 的关系：
--   菜单与权限**不在** doc/main/mysql-ddl-member-level-price.sql 里（那份只做表结构、
--   定时任务与业务类型注释），这里单独一份，理由与 mysql-menu-goods-order.sql 一致：
--   换环境 / 重装时只想补菜单，不想碰建表与任务。
--
-- 执行顺序：Part 1 菜单 → Part 2 角色授权（可选）→ Part 3 自检
-- 目标库：与 .env 的 DB_DATABASE 一致；MySQL 8.0.19+（upsert 别名语法）
-- 幂等性：菜单行用 `AS new ON DUPLICATE KEY UPDATE`（命中 id 主键只覆盖展示字段）；
--   sys_role_menu 只有主键、没有 (role_id, menu_id) 唯一键，故授权段先 DELETE 再 INSERT。
--   整段可重复执行，不会报错、不会产生重复行。
--
-- id 段：会员模块页面固定在 `10000000-0000-0000-0000-0000000010xx` 段，
--   ...1000 目录 / ...1001~1005 会员等级 / ...1011~1018 会员管理 / ...1021~1026 优惠码 /
--   ...1031~1036 充值记录 / ...1041~1045 消费冻结单 / ...1051~1056 余额流水
--   （...20xx 是 sys_job 任务段，不要用）。
--   本脚本占用 ...1061~1065，已核对空闲。
-- 目录内 sort_order：兄弟页面已用 1（会员等级）、2（会员管理）、3（优惠码）、
--   4（充值记录）、5（消费冻结单）、6（余额流水），故本页取 7 排在末位（自检会打印）。
-- ============================================================================


-- ============================================================================
-- Part 1：菜单（1 页面 + 4 按钮权限 = 5 行）
--
-- 权限码与 shared/system/memberLevelOrder/input.ts、后端路由一一对应：
--   list  查询（列表 / 详情）
--   edit  关闭未支付单（仅 WP 可关）
--   query 同步支付状态（有副作用：向渠道查询并推进单据，故单独授权）
--   del   删除
--
-- 图标用 i-lucide-receipt：i-lucide-crown 已被「会员等级」(…1001) 占用，避免侧边栏视觉重复。
-- ============================================================================

INSERT INTO `sys_menu`
  (`id`, `parent_id`, `name`, `code`, `type`, `path`, `component`, `icon`, `sort_order`, `visible`, `status`, `remark`, `created_by`, `updated_by`, `is_deleted`)
VALUES
  -- 页面
  ('10000000-0000-0000-0000-000000001061', '10000000-0000-0000-0000-000000001000', '会员开通记录', 'system:memberLevelOrder', 1, '/system/member-level-order', 'system/member-level-order/index', 'i-lucide-receipt', 7, 0, 1, '会员等级购买 / 续费开通单', '30000000-0000-0000-0000-000000000001', '30000000-0000-0000-0000-000000000001', 0),

  -- 按钮权限
  ('10000000-0000-0000-0000-000000001062', '10000000-0000-0000-0000-000000001061', '开通记录查询', 'system:memberLevelOrder:list', 2, NULL, NULL, NULL, 1, 1, 1, NULL, '30000000-0000-0000-0000-000000000001', '30000000-0000-0000-0000-000000000001', 0),
  ('10000000-0000-0000-0000-000000001063', '10000000-0000-0000-0000-000000001061', '关闭开通单', 'system:memberLevelOrder:edit', 2, NULL, NULL, NULL, 2, 1, 1, '仅待支付单可关闭', '30000000-0000-0000-0000-000000000001', '30000000-0000-0000-0000-000000000001', 0),
  ('10000000-0000-0000-0000-000000001064', '10000000-0000-0000-0000-000000001061', '同步支付状态', 'system:memberLevelOrder:query', 2, NULL, NULL, NULL, 3, 1, 1, '有副作用：向渠道查询并推进单据，故单独授权', '30000000-0000-0000-0000-000000000001', '30000000-0000-0000-0000-000000000001', 0),
  ('10000000-0000-0000-0000-000000001065', '10000000-0000-0000-0000-000000001061', '开通记录删除', 'system:memberLevelOrder:del', 2, NULL, NULL, NULL, 4, 1, 1, NULL, '30000000-0000-0000-0000-000000000001', '30000000-0000-0000-0000-000000000001', 0)
AS new
ON DUPLICATE KEY UPDATE
  `parent_id` = new.parent_id,
  `name` = new.name,
  `code` = new.code,
  `type` = new.type,
  `path` = new.path,
  `component` = new.component,
  `icon` = new.icon,
  `sort_order` = new.sort_order,
  `visible` = new.visible,
  `status` = new.status,
  `remark` = new.remark,
  `updated_by` = new.updated_by,
  `is_deleted` = new.is_deleted;


-- ============================================================================
-- Part 2：角色授权（可选）
--
-- 说明：
-- - 管理员账号（sys_user.is_admin = 1）走「全量菜单」分支，不需要任何授权；
-- - 其它角色只有在 sys_role_menu 里有记录才会看到对应菜单与权限；
-- - sys_role_menu 只有主键、没有 (role_id, menu_id) 唯一键，所以幂等做法是
--   「先删掉这批 (角色 × 菜单) 关联，再统一插入」——因此下面是 DELETE + INSERT 两段。
--
-- 授权矩阵（运营可关单与同步状态，删除仍只属于管理员）：
--   部门经理 dept_manager：页面 + :list + :edit(关闭) + :query(同步)
--   业务运营 operator    ：同上
--   审计员   auditor     ：页面 + :list（只读）
--   访客     guest       ：不授
-- 如需调整，改下面的 role id 列表或菜单 id 列表即可。
-- ============================================================================

-- 2.1 清掉本脚本负责的这批关联（可重复执行的关键）
DELETE FROM `sys_role_menu`
WHERE `menu_id` IN (
  '10000000-0000-0000-0000-000000001061',
  '10000000-0000-0000-0000-000000001062',
  '10000000-0000-0000-0000-000000001063',
  '10000000-0000-0000-0000-000000001064',
  '10000000-0000-0000-0000-000000001065'
)
AND `role_id` IN (
  '20000000-0000-0000-0000-000000000002',
  '20000000-0000-0000-0000-000000000003',
  '20000000-0000-0000-0000-000000000004'
);

-- 2.2 部门经理 / 业务运营：页面 + 查询 + 关闭 + 同步
INSERT INTO `sys_role_menu`
  (`id`, `role_id`, `menu_id`, `status`, `remark`, `created_by`, `updated_by`, `is_deleted`)
SELECT UUID(), r.`id`, m.`id`, 1, '会员开通记录菜单授权',
       '30000000-0000-0000-0000-000000000001', '30000000-0000-0000-0000-000000000001', 0
FROM `sys_role` r
JOIN `sys_menu` m ON m.`id` IN (
  '10000000-0000-0000-0000-000000001061',
  '10000000-0000-0000-0000-000000001062',
  '10000000-0000-0000-0000-000000001063',
  '10000000-0000-0000-0000-000000001064'
)
WHERE r.`id` IN (
  '20000000-0000-0000-0000-000000000002',
  '20000000-0000-0000-0000-000000000003'
)
AND r.`is_deleted` = 0;

-- 2.3 审计员：页面 + 查询（只读，不给关闭 / 同步 / 删除）
INSERT INTO `sys_role_menu`
  (`id`, `role_id`, `menu_id`, `status`, `remark`, `created_by`, `updated_by`, `is_deleted`)
SELECT UUID(), r.`id`, m.`id`, 1, '会员开通记录菜单授权',
       '30000000-0000-0000-0000-000000000001', '30000000-0000-0000-0000-000000000001', 0
FROM `sys_role` r
JOIN `sys_menu` m ON m.`id` IN (
  '10000000-0000-0000-0000-000000001061',
  '10000000-0000-0000-0000-000000001062'
)
WHERE r.`id` = '20000000-0000-0000-0000-000000000004'
AND r.`is_deleted` = 0;


-- ============================================================================
-- Part 3：执行结果自检
-- 预期：菜单 5 行；授权行数 = 4×2 + 2 = 10
-- ============================================================================

-- 3.1 菜单行数：应为 5
SELECT COUNT(*) AS `会员开通记录菜单行数(应为5)` FROM `sys_menu`
WHERE `id` IN (
  '10000000-0000-0000-0000-000000001061',
  '10000000-0000-0000-0000-000000001062',
  '10000000-0000-0000-0000-000000001063',
  '10000000-0000-0000-0000-000000001064',
  '10000000-0000-0000-0000-000000001065'
);

-- 3.2 id 冲突核对：...1060~...1069 段只应有上面的 5 行（多出来的就是冲突，需人工处理）
SELECT `id`, `parent_id`, `name`, `code`, `type`, `sort_order`
FROM `sys_menu`
WHERE `id` BETWEEN '10000000-0000-0000-0000-000000001060' AND '10000000-0000-0000-0000-000000001069'
ORDER BY `id`;

-- 3.3 页面行核对（含目录内排序 sort_order，预期 7）
SELECT `id`, `parent_id`, `name`, `code`, `type`, `path`, `component`, `icon`, `sort_order`, `visible`, `status`
FROM `sys_menu`
WHERE `id` = '10000000-0000-0000-0000-000000001061';

-- 3.4 目录内页面排序全景（预期 1~7 连续，本页排最后）
SELECT `id`, `name`, `code`, `sort_order`
FROM `sys_menu`
WHERE `parent_id` = '10000000-0000-0000-0000-000000001000' AND `type` = 1
ORDER BY `sort_order`, `id`;

-- 3.5 授权行数：预期 dept_manager 4 / operator 4 / auditor 2
SELECT r.`code` AS `角色`, COUNT(*) AS `授权菜单数`
FROM `sys_role_menu` rm
JOIN `sys_role` r ON r.`id` = rm.`role_id`
WHERE rm.`menu_id` IN (
  '10000000-0000-0000-0000-000000001061',
  '10000000-0000-0000-0000-000000001062',
  '10000000-0000-0000-0000-000000001063',
  '10000000-0000-0000-0000-000000001064',
  '10000000-0000-0000-0000-000000001065'
)
GROUP BY r.`code`
ORDER BY r.`code`;

-- 3.6 权限码清单（供后端路由 / 前端按钮逐一对齐）
SELECT `code`, `name`, `type`
FROM `sys_menu`
WHERE `id` IN (
  '10000000-0000-0000-0000-000000001061',
  '10000000-0000-0000-0000-000000001062',
  '10000000-0000-0000-0000-000000001063',
  '10000000-0000-0000-0000-000000001064',
  '10000000-0000-0000-0000-000000001065'
)
ORDER BY `type`, `id`;

-- 3.7 侧边栏可见性核对：会员管理目录 + 类型不为按钮的页面
SELECT `id`, `parent_id`, `name`, `code`, `type`, `path`, `sort_order`, `visible`, `status`
FROM `sys_menu`
WHERE `id` LIKE '10000000-0000-0000-0000-0000000010%' AND `type` IN (0, 1)
ORDER BY `sort_order`, `id`;
